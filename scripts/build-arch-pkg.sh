#!/usr/bin/env bash
# Builds the Arch Linux package remoteflow-X.Y.Z-1-x86_64.pkg.tar.zst from an already compiled
# program (the same binary as the portable build). Runs on any Linux with bsdtar (libarchive-tools)
# and zstd, so the Ubuntu release runner and the Docker build can make it – no makepkg needed.
#
# Usage: bash scripts/build-arch-pkg.sh [BINARY] [OUTPUT_DIR]
#   BINARY      default: src-tauri/target/release/remoteflow
#   OUTPUT_DIR  default: current directory
#
# Installed with `sudo pacman -U ./remoteflow-…pkg.tar.zst`. The program recognises the pacman
# installation (install.rs) and does not update itself – a new version is installed the same way.
set -euo pipefail

root="$(cd -- "$(dirname -- "$0")/.." && pwd)"
binary="${1:-$root/src-tauri/target/release/remoteflow}"
out_dir="${2:-$PWD}"

for tool in bsdtar zstd gzip; do
  command -v "$tool" >/dev/null || { printf 'Missing tool: %s (Debian/Ubuntu: apt install libarchive-tools zstd)\n' "$tool" >&2; exit 1; }
done
[[ -f "$binary" ]] || { printf 'Program not found: %s\n' "$binary" >&2; exit 1; }
mkdir -p -- "$out_dir"
out_dir="$(cd -- "$out_dir" && pwd)"

version="$(sed -nE 's/^[[:space:]]*"version":[[:space:]]*"([^"]+)".*/\1/p' "$root/package.json" | head -n1)"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { printf 'Unexpected version in package.json: %s\n' "$version" >&2; exit 1; }
pkgrel="${PKGREL:-1}"
pkgfile="remoteflow-${version}-${pkgrel}-x86_64.pkg.tar.zst"

stage="$(mktemp -d)"
trap 'rm -rf -- "$stage"' EXIT
umask 022

install -Dm755 "$binary" "$stage/usr/bin/remoteflow"
install -Dm644 "$root/src-tauri/icons/32x32.png" "$stage/usr/share/icons/hicolor/32x32/apps/remoteflow.png"
install -Dm644 "$root/src-tauri/icons/128x128.png" "$stage/usr/share/icons/hicolor/128x128/apps/remoteflow.png"
install -Dm644 "$root/src-tauri/icons/128x128@2x.png" "$stage/usr/share/icons/hicolor/256x256/apps/remoteflow.png"
install -Dm644 "$root/src-tauri/icons/icon.png" "$stage/usr/share/icons/hicolor/512x512/apps/remoteflow.png"
install -Dm644 "$root/LICENSE" "$stage/usr/share/licenses/remoteflow/LICENSE"
install -dm755 "$stage/usr/share/applications"
cat > "$stage/usr/share/applications/remoteflow.desktop" <<'EOF'
[Desktop Entry]
Type=Application
Name=RemoteFlow
Comment=SSH, SFTP and RDP connection manager
Exec=remoteflow
Icon=remoteflow
Terminal=false
Categories=Development;Network;
StartupWMClass=remoteflow
EOF
chmod 644 "$stage/usr/share/applications/remoteflow.desktop"

# Reproducible timestamps: the commit time in CI (SOURCE_DATE_EPOCH), otherwise now
builddate="${SOURCE_DATE_EPOCH:-$(date +%s)}"
size="$(du -sb --apparent-size "$stage/usr" | cut -f1)"

# Dependencies = the libraries the program links (readelf -d … NEEDED) plus the trash/clipboard helpers
cat > "$stage/.PKGINFO" <<EOF
# Generated by scripts/build-arch-pkg.sh
pkgname = remoteflow
pkgbase = remoteflow
pkgver = ${version}-${pkgrel}
pkgdesc = SSH, SFTP and RDP connection manager with an encrypted vault
url = https://github.com/jacek-nikiel/RemoteFlow
builddate = ${builddate}
packager = RemoteFlow release workflow <https://github.com/jacek-nikiel/RemoteFlow>
size = ${size}
arch = x86_64
license = MIT
provides = remoteflow
conflict = remoteflow-bin
conflict = remoteflow-git
depend = webkit2gtk-4.1
depend = gtk3
depend = libsoup3
depend = cairo
depend = gdk-pixbuf2
depend = glib2
depend = libx11
depend = dbus
depend = openssl
depend = zlib
depend = gcc-libs
depend = glibc
depend = hicolor-icon-theme
optdepend = freerdp: RDP connections
optdepend = xorg-xwayland: embedded RDP window under Wayland
optdepend = which: finding the FreeRDP program
optdepend = openssh: SSH agent and OpenSSH keys
optdepend = zenity: file dialogs on GNOME and other GTK desktops
optdepend = kdialog: file dialogs on KDE Plasma
optdepend = wl-clipboard: copying files to the clipboard under Wayland
optdepend = xclip: copying files to the clipboard under X11
EOF

(
  cd "$stage"
  find . -exec touch -h -d "@$builddate" {} +
  # File list for pacman -Qk (same options as makepkg)
  LANG=C bsdtar -cf - --format=mtree --uid 0 --gid 0 --uname root --gname root \
    --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
    .PKGINFO usr | gzip -c -f -n > .MTREE
  touch -d "@$builddate" .MTREE
  LANG=C bsdtar -cf - --uid 0 --gid 0 --uname root --gname root .PKGINFO .MTREE usr \
    | zstd -q -19 -T0 -f -o "$out_dir/$pkgfile"
)

printf 'Arch Linux package: %s\n' "$out_dir/$pkgfile"
